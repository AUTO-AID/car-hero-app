/**
 * السنوات من الأحدث إلى الأقدم. الخادم يقبل حتى ١٩٠٠، لكن قائمة بمئة سنة
 * عبء إدراكي بلا مقابل — نعرض ٤٠ سنة ويبقى الإدخال اليدوي متاحاً لما قبلها.
 */
export function yearOptions(count = 40) {
  const max = new Date().getFullYear() + 1;
  return Array.from({ length: count }, (_, index) => String(max - index));
}
