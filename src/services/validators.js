// كلمة المرور: 8 رموز على الأقل + حرف كبير + حرف صغير + رقم + رمز خاص
export const PASSWORD_RULE = /^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)(?=.*[^A-Za-z0-9]).{8,}$/;

export function isStrongPassword(pw) {
  return PASSWORD_RULE.test(pw || '');
}
